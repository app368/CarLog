// Задача: один пункт плана работ — английское название, русское и пояснение (может быть в несколько строк)
struct ServicePlanItem: Identifiable {
    let english: String
    let russian: String
    let text: String

    var id: String { english }

    init(_ english: String, _ russian: String, _ text: String) {
        self.english = english
        self.russian = russian
        self.text = text
    }
}

